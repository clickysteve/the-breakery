/**
 * `npm run evaluate`: also writes docs/chop-report.md. Representative GROOVEs (FUNK, HIP-HOP,
 * JUNGLE, D&B, BREAKCORE, several seeds) beside LOW, MEDIUM and HIGH CHOP, as grids, with a few
 * structural measures per recipe: how much of the GROOVE is still where it was, whether the
 * backbeat survives, how much of the result is retriggers, and that ghosts stay soft. The grids are
 * for reading; measures cannot say whether a chop sounds good, only listening can.
 */
import { writeFileSync } from 'node:fs';
import { test } from 'vitest';
import { asciiGrid } from '../src/engine/ascii';
import { describeChop } from '../src/engine/chopper';
import { bake, seedsFrom } from '../src/engine/generate';
import { defaultRecipe, STYLE_DEFS } from '../src/engine/styles';
import { TPB, TPS, type Bars, type Break, type ChopSettings, type SliceSize, type Style } from '../src/engine/types';

const STYLES: Style[] = ['funk', 'hiphop', 'jungle', 'dnb', 'breakcore'];
const SEEDS = [101, 202, 303];
const LEVELS: [string, Partial<ChopSettings>][] = [
  ['LOW', { amount: 0.25, retrigger: 0.15 }],
  ['MEDIUM', { amount: 0.55, retrigger: 0.35 }],
  ['HIGH', { amount: 0.9, retrigger: 0.7 }],
];
/** the slice size each recipe is shown with (the one its producers would reach for) */
const SLICE: Record<string, SliceSize> = { funk: 'large', hiphop: 'medium', jungle: 'small', dnb: 'medium', breakcore: 'micro' };

const key = (e: Break['events'][number]) => `${e.cat}|${e.bar * TPB + e.step * TPS + e.sub}`;
const pct = (x: number) => `${Math.round(x * 100)}%`;
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);

function bakeChop(style: Style, seed: number, bars: Bars, c: Partial<ChopSettings> | null): Break {
  const r = defaultRecipe(style, bars);
  return bake(c ? { ...r, chop: { on: true, amount: 0, slice: SLICE[style]!, retrigger: 0, variant: 0, ...c } } : r, seedsFrom(seed));
}

/** share of the GROOVE's hits still at their place; backbeats kept; retrigger share; loudest ghost */
function measure(src: Break, out: Break) {
  const a = new Set(src.events.map(key));
  const kept = out.events.filter((e) => a.has(key(e))).length / Math.max(1, src.events.length);
  const bb = src.events.filter((e) => e.cat === 'snare' && (e.role === 'backbeat' || e.role === 'displaced backbeat'));
  const bbKept = bb.filter((b) => out.events.some((e) => e.cat === 'snare' && e.bar === b.bar && e.step === b.step)).length / Math.max(1, bb.length);
  const newRolls = out.events.filter((e) => e.role === 'roll' && e.why.startsWith('CHOP retrigger')).length / Math.max(1, out.events.length);
  const ghost = Math.max(0, ...out.events.filter((e) => e.cat === 'ghost').map((e) => e.vel));
  return { kept, bbKept, newRolls, ghost, hits: out.events.length / Math.max(1, src.events.length) };
}

test('chop report', () => {
  const lines: string[] = [
    '# CHOP: representative results',
    '',
    'Generated by `npm run evaluate` (scripts/evaluate-chop.test.ts). Each block is one GROOVE (recipe defaults, 4 bars) and the same GROOVE at LOW (AMOUNT 25%, RETRIGGER 15%), MEDIUM (55%, 35%) and HIGH (90%, 70%) CHOP, at the slice size shown. Grid: `X` loud, `x` medium, `o` soft, `-` ghost-quiet, `~` a hit off the sixteenth grid (a 32nd, a triplet or a roll stroke), `.` a beat with nothing on it.',
    '',
    'These are structural checks and something to read; they are not a listening test.',
    '',
    '## Measures (mean over 12 seeds, 4 bars)',
    '',
    '| Recipe | Slice | Level | GROOVE hits still in place | Backbeats kept | Hits from new retriggers | Hit count vs GROOVE | Loudest ghost |',
    '|---|---|---|---|---|---|---|---|',
  ];
  for (const s of STYLES) {
    for (const [name, c] of LEVELS) {
      const ms = Array.from({ length: 12 }, (_, i) => 500 + i).map((seed) => measure(bakeChop(s, seed, 4, null), bakeChop(s, seed, 4, c)));
      lines.push(`| ${STYLE_DEFS[s].label} | ${SLICE[s]!.toUpperCase()} | ${name} | ${pct(mean(ms.map((m) => m.kept)))} | ${pct(mean(ms.map((m) => m.bbKept)))} | ${pct(mean(ms.map((m) => m.newRolls)))} | ${pct(mean(ms.map((m) => m.hits)))} | ${Math.max(...ms.map((m) => m.ghost))} |`);
    }
  }
  lines.push('');
  for (const s of STYLES) {
    lines.push(`## ${STYLE_DEFS[s].label} (slice ${SLICE[s]!.toUpperCase()})`, '');
    for (const seed of SEEDS) {
      const src = bakeChop(s, seed, 4, null);
      lines.push(`### seed ${seed}`, '', '```', 'GROOVE', asciiGrid(src));
      for (const [name, c] of LEVELS) {
        const b = bakeChop(s, seed, 4, c);
        lines.push('', `${name}: ${describeChop(b.chop)}`, asciiGrid(b));
      }
      lines.push('```', '');
    }
  }
  writeFileSync('docs/chop-report.md', lines.join('\n') + '\n');
});
