/**
 * `npm run evaluate`: also writes docs/tom-report.md. TOM ACTIVITY at 0, 20, 50, 75 and 100% in
 * FUNK, HIP-HOP, JUNGLE, BROKEN, D&B and BREAKCORE (recipe defaults, 4 and 8 bars, 40 seeds),
 * before (revision 0, the tom fills as released, ROLLS as the recipe had them) and after
 * (revision 1, tom phrases, ROLL GENERATION off as for a new user), with a few structural measures
 * and grids at 100%. Tom rolls from the ROLLS layer are not counted: they belong to ROLLS. The
 * measures say how much and where; whether the toms sound good needs listening.
 */
import { writeFileSync } from 'node:fs';
import { test } from 'vitest';
import { asciiGrid } from '../src/engine/ascii';
import { bake, seedsFrom } from '../src/engine/generate';
import { emptyKit, type KitIndex } from '../src/engine/kit';
import { defaultRecipe, STYLE_DEFS } from '../src/engine/styles';
import { CATEGORIES, CURRENT_REVISION, isTom, STEPS, TPB, TPS, type Bars, type Break, type BreakEvent, type Recipe, type Style } from '../src/engine/types';

const STYLES: Style[] = ['funk', 'hiphop', 'jungle', 'broken', 'dnb', 'breakcore'];
const LEVELS = [0, 0.2, 0.5, 0.75, 1];
const SEEDS = Array.from({ length: 40 }, (_, i) => 700 + i);
const kit = (): KitIndex => {
  const k = emptyKit();
  for (const c of CATEGORIES) k[c] = [`${c}-a`];
  return k;
};
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / Math.max(1, xs.length);
const f1 = (x: number) => x.toFixed(1);
const pct = (x: number) => `${Math.round(x * 100)}%`;
const tick = (e: BreakEvent) => e.bar * TPB + e.step * TPS + e.sub;
const toms = (b: Break) => b.events.filter((e) => isTom(e.cat) && e.role !== 'roll');
const backbeat = (e: BreakEvent) => e.cat === 'snare' && (e.role === 'backbeat' || e.role === 'displaced backbeat');

type Era = 'before' | 'after';
function recipe(style: Style, bars: Bars, t: number, era: Era, patch: Partial<Recipe> = {}): Recipe {
  const r = { ...defaultRecipe(style, bars), toms: t, ...patch };
  return era === 'before' ? { ...r, revision: 0 } : { ...r, revision: CURRENT_REVISION, rollsOn: false };
}

/** tom hits; phrases (a new one after a gap of more than an eighth, or a new bar); toms used; bars with toms; share in the last bar; share in the last beat of a bar; unisons with a kick; clashes with a backbeat */
function measure(b: Break) {
  const t = toms(b);
  const bars = b.recipe.bars;
  let phrases = 0;
  for (let bar = 0; bar < bars; bar++) {
    const st = t.filter((e) => e.bar === bar).map((e) => e.step).sort((x, y) => x - y);
    st.forEach((x, i) => (i === 0 || x - st[i - 1]! > 2) && phrases++);
  }
  const kicks = new Set(b.events.filter((e) => e.cat === 'kick').map(tick));
  const bbs = new Set(b.events.filter(backbeat).map(tick));
  return {
    hits: t.length,
    few: t.length <= 2 ? 1 : 0,
    phrases,
    voices: new Set(t.map((e) => e.cat)).size,
    bars: new Set(t.map((e) => e.bar)).size,
    last: t.length ? t.filter((e) => e.bar === bars - 1).length / t.length : 0,
    ending: t.length ? t.filter((e) => e.step >= STEPS - 4).length / t.length : 0,
    unison: t.filter((e) => kicks.has(tick(e))).length,
    clash: t.filter((e) => bbs.has(tick(e))).length,
  };
}
type M = ReturnType<typeof measure>;
const avg = (ms: M[]) => ({
  hits: mean(ms.map((m) => m.hits)),
  few: mean(ms.map((m) => m.few)),
  phrases: mean(ms.map((m) => m.phrases)),
  voices: mean(ms.map((m) => m.voices)),
  bars: mean(ms.map((m) => m.bars)),
  last: mean(ms.filter((m) => m.hits).map((m) => m.last)),
  ending: mean(ms.filter((m) => m.hits).map((m) => m.ending)),
  unison: mean(ms.map((m) => m.unison)),
  clash: ms.reduce((n, m) => n + m.clash, 0),
});
const run = (style: Style, bars: Bars, t: number, era: Era, patch: Partial<Recipe> = {}) => avg(SEEDS.map((s) => measure(bake(recipe(style, bars, t, era, patch), seedsFrom(s), kit()))));

test('tom report', () => {
  const head = '| Recipe | TOM ACTIVITY | Tom hits before → after | Patterns with ≤ 2 tom hits | Phrases | Toms used | Bars with toms | In the last bar | In the last beat of a bar | With a kick | On a backbeat |';
  const rule = '|---|---|---|---|---|---|---|---|---|---|---|';
  const row = (label: string, t: number, b: ReturnType<typeof avg>, a: ReturnType<typeof avg>) =>
    `| ${label} | ${pct(t)} | ${f1(b.hits)} → **${f1(a.hits)}** | ${pct(b.few)} → ${pct(a.few)} | ${f1(b.phrases)} → ${f1(a.phrases)} | ${f1(b.voices)} → ${f1(a.voices)} | ${f1(b.bars)} → ${f1(a.bars)} | ${pct(b.last)} → ${pct(a.last)} | ${pct(b.ending)} → ${pct(a.ending)} | ${f1(b.unison)} → ${f1(a.unison)} | ${b.clash} → ${a.clash} |`;

  const lines: string[] = [
    '# TOM ACTIVITY: before and after',
    '',
    'Generated by `npm run evaluate` (scripts/evaluate-toms.test.ts). Each row is the mean over 40 seeds of one recipe at its defaults with TOM ACTIVITY set as shown, on a kit with all three toms. **Before** is revision 0: the tom fills as released, with ROLLS as the recipe had them. **After** is revision 1: tom phrases, with ROLL GENERATION off as for a new user. Tom rolls from the ROLLS layer are not counted in either: they belong to ROLLS.',
    '',
    'Columns: tom hits in the pattern; the share of patterns left with two tom hits or fewer; phrases (a new phrase after a gap of more than an eighth, or in a new bar); how many of the three toms are used; how many bars have toms; the share of tom hits in the last bar and in the last beat of any bar (phrase endings); tom hits played with a kick; and tom hits on a backbeat (in total, over all seeds; a tom never replaces the backbeat).',
    '',
    'These are structural measures and something to read; they are not a listening test.',
    '',
    '## The reported case: BROKEN, 126 BPM, 4 bars, DENSITY 75%, COMPLEXITY 65%, FILLS 75%',
    '',
    head,
    rule,
  ];
  const reported: Partial<Recipe> = { bpm: 126, density: 0.75, complexity: 0.65, fills: 0.75 };
  for (const t of LEVELS) lines.push(row('BROKEN', t, run('broken', 4, t, 'before', reported), run('broken', 4, t, 'after', reported)));
  for (const bars of [4, 8] as Bars[]) {
    lines.push('', `## Recipe defaults, ${bars} bars`, '', head, rule);
    for (const s of STYLES) for (const t of LEVELS) lines.push(row(STYLE_DEFS[s].label, t, run(s, bars, t, 'before'), run(s, bars, t, 'after')));
  }
  lines.push('', '## Grids at 100% (4 bars, after)', '', 'Grid: `X` loud, `x` medium, `o` soft, `-` ghost-quiet, `~` a hit off the sixteenth grid, `.` a beat with nothing on it.', '');
  for (const s of STYLES)
    for (const seed of SEEDS.slice(0, 2)) {
      const b = bake(recipe(s, 4, 1, 'after'), seedsFrom(seed), kit());
      lines.push(`### ${STYLE_DEFS[s].label}, seed ${seed}`, '', '```', asciiGrid(b), '```', '');
      for (const e of toms(b).filter((x, i, all) => i === 0 || all[i - 1]!.why !== x.why)) lines.push(`- bar ${e.bar + 1}, step ${e.step + 1}: ${e.why}`);
      lines.push('');
    }
  writeFileSync('docs/tom-report.md', lines.join('\n') + '\n');
});
